// Regenerates src/st-registry.js from SillyTavern's macro registry.
// Usage: ST_DIR=/path/to/SillyTavern node tools/st-harness/setup.mjs
//        node --import ./tools/st-harness/.work/register.mjs tools/dump-st-registry.mjs
import { writeFileSync } from 'node:fs';
import './st-harness/.work/st-engine.mjs';

const { MacroRegistry } = await import('./st-harness/.work/pub/scripts/macros/engine/MacroRegistry.js');
const lines = [];
for (const d of MacroRegistry.getAllMacros()) {
  // Only non-string argument types can make SillyTavern reject a call.
  const types = d.unnamedArgDefs.map((a) => {
    const t = Array.isArray(a.type) ? a.type : [a.type];
    return t.includes('string') ? null : t;
  });
  const typed = types.some(Boolean) ? JSON.stringify(types) : 'null';
  lines.push(`  ${JSON.stringify(d.name)}: [${d.minArgs}, ${d.maxArgs}, ${d.list ? JSON.stringify([d.list.min, d.list.max]) : 'null'}, ${d.strictArgs}, ${d.aliasOf ? JSON.stringify(d.aliasOf) : 'null'}, ${typed}],`);
}
const source = `/* SillyTavern macro arities: name: [minArgs, maxArgs, list [min, max] or null, strictArgs, aliasOf, argTypes].
 * argTypes lists the accepted types per positional argument (null = any string).
 * Generated by tools/dump-st-registry.mjs from the SillyTavern macro registry; regenerate when ST adds macros. */
const ST_MACROS = {
${lines.join('\n')}
};
`;
writeFileSync(new URL('../src/st-registry.js', import.meta.url), source);
console.log(`Wrote ${lines.length} macros to src/st-registry.js`);
